//! Prints `src/canonical/tables.rs`, the Unicode data `canonical.rs` decomposes names with.
//!
//! `cargo run -p bravebot-core --example canonical_tables > crates/core/src/canonical/tables.rs`
//!
//! The data is read from the `unicode-normalization` crate, the same one the module's tests
//! compare every code point against, so a release of it that moves to another Unicode version
//! fails that test until the tables are written again with this.

#![forbid(unsafe_code)]

use unicode_normalization::UNICODE_VERSION;
use unicode_normalization::char::{canonical_combining_class, decompose_canonical};

/// A Hangul syllable decomposes by arithmetic, so the table does not hold it.
const HANGUL: std::ops::RangeInclusive<u32> = 0xAC00..=0xD7A3;

fn main() {
    let (major, minor, update) = UNICODE_VERSION;
    println!(
        "//! Unicode {major}.{minor}.{update} canonical decompositions and combining classes."
    );
    println!("//!");
    println!(
        "//! Generated by `cargo run -p bravebot-core --example canonical_tables`. Do not edit."
    );
    println!();

    println!(
        "/// Each code point with a canonical decomposition and the whole of it, by code point."
    );
    println!("pub(super) static DECOMPOSITIONS: &[(u32, &[u32])] = &[");
    let mut line = String::new();
    for code in 0x80u32..=0x10FFFF {
        let Some(c) = char::from_u32(code) else {
            continue;
        };
        if HANGUL.contains(&code) {
            continue;
        }
        let mut parts = Vec::new();
        decompose_canonical(c, |part| parts.push(part as u32));
        if parts == [code] {
            continue;
        }
        let listed: Vec<String> = parts.iter().map(|part| format!("{part:#06X}")).collect();
        push(
            &mut line,
            format!("({code:#06X}, &[{}]),", listed.join(", ")),
        );
    }
    flush(&mut line);
    println!("];");
    println!();

    println!("/// Runs of code points sharing a nonzero combining class: first, last and class.");
    println!("pub(super) static COMBINING_CLASSES: &[(u32, u32, u8)] = &[");
    let mut run: Option<(u32, u32, u8)> = None;
    let mut line = String::new();
    for code in 0x80u32..=0x10FFFF {
        let class = char::from_u32(code).map_or(0, canonical_combining_class);
        run = match (run, class) {
            (Some((first, last, held)), class) if class == held && last + 1 == code => {
                Some((first, code, held))
            }
            (finished, class) => {
                if let Some((first, last, held)) = finished {
                    push(&mut line, format!("({first:#06X}, {last:#06X}, {held}),"));
                }
                (class != 0).then_some((code, code, class))
            }
        };
    }
    if let Some((first, last, held)) = run {
        push(&mut line, format!("({first:#06X}, {last:#06X}, {held}),"));
    }
    flush(&mut line);
    println!("];");
}

/// Add an entry to the line being filled, starting a new line when the entry would take it past
/// 96 columns. `flush` indents a line by four more, which keeps each generated line within
/// rustfmt's 100.
fn push(line: &mut String, entry: String) {
    if !line.is_empty() && line.len() + 1 + entry.len() > 96 {
        flush(line);
    }
    if !line.is_empty() {
        line.push(' ');
    }
    line.push_str(&entry);
}

fn flush(line: &mut String) {
    if !line.is_empty() {
        println!("    {line}");
        line.clear();
    }
}
