// The desktop window's messages, written out as TypeScript.
//
// The messages whose ids start `ui-` are the window's chrome. They live in the same catalogs as
// the terminal's, so the same checks hold them (LOCALE-3), and are turned into one function per
// message per catalog, committed as `ui/src/renderer/i18n/messages.gen.ts`. The window holds
// finished text and the code that concatenates it, as the terminal does (LOCALE-6), and reaches a
// message by a property the compiler checks (LOCALE-2). A test fails while the committed file
// differs from what the catalogs say; `BLESS=1` rewrites it.

use crate::catalog::*;
use crate::generate::Catalog;

/// The prefix that puts a message in the window.
pub const PREFIX: &str = "ui-";

/// Where the generated file is committed, from the crate's directory.
pub const OUTPUT: &str = "../../ui/src/renderer/i18n/messages.gen.ts";

/// The whole of `messages.gen.ts`.
pub fn typescript(catalogs: &[Catalog], reference: &Catalog) -> String {
    let ids: Vec<&String> = reference
        .messages
        .keys()
        .filter(|id| id.starts_with(PREFIX))
        .collect();

    let mut out = String::from(
        "// Generated by crates/i18n/src/typescript.rs from the ui- messages in crates/i18n/locales/*.ftl.\n\
         // Do not edit. After changing a catalog, run `BLESS=1 cargo test -p bravebot-i18n` and commit this file.\n",
    );

    let mut languages: Vec<&str> = Vec::new();
    for catalog in catalogs {
        for id in &ids {
            let from = if catalog.messages.contains_key(*id) {
                catalog
            } else {
                reference
            };
            if selects(&from.messages[*id].value) && !languages.contains(&from.language.as_str()) {
                languages.push(&from.language);
            }
        }
    }
    if !languages.is_empty() {
        out.push_str("\nconst plural = {\n");
        for language in &languages {
            out.push_str(&format!(
                "  {}: new Intl.PluralRules({}),\n",
                language,
                quoted(language)
            ));
        }
        out.push_str("}\n");
    }

    for catalog in catalogs {
        let name = binding(catalog);
        if catalog.tag == reference.tag {
            out.push_str(&format!("\nconst {name} = {{\n"));
        } else {
            out.push_str(&format!("\nconst {name}: Messages = {{\n"));
        }
        for id in &ids {
            let property = property(id);
            match catalog.messages.get(*id) {
                Some(message) => out.push_str(&format!(
                    "  {property}: {},\n",
                    function(&message.value, &catalog.language)
                )),
                None => out.push_str(&format!(
                    "  {property}: {}.{property},\n",
                    binding(reference)
                )),
            }
        }
        out.push_str("}\n");
        if catalog.tag == reference.tag {
            out.push_str(&format!(
                "\n/** Every message the window says, by the name it has in the catalog. */\nexport type Messages = typeof {name}\n"
            ));
        }
    }

    out.push_str(
        "\n/** Every catalog that shipped, reference first. */\nexport const CATALOGS = {\n",
    );
    for catalog in catalogs {
        out.push_str(&format!(
            "  {}: {},\n",
            quoted(&catalog.tag),
            binding(catalog)
        ));
    }
    out.push_str("} as const satisfies Record<string, Messages>\n");
    out.push_str("\nexport type Tag = keyof typeof CATALOGS\n");
    out.push_str(&format!(
        "\nexport const REFERENCE: Tag = {}\n",
        quoted(&reference.tag)
    ));
    out
}

fn selects(value: &Value) -> bool {
    match value {
        Value::Pattern(_) => false,
        Value::Select {
            variants, default, ..
        } => variants
            .iter()
            .any(|variant| variant.parts != variants[*default].parts),
    }
}

/// `en-US` as the name of the constant that holds its messages.
fn binding(catalog: &Catalog) -> String {
    format!("catalog{}", camel_case(&catalog.tag.to_lowercase()))
}

/// `ui-settings-theme` as `uiSettingsTheme`.
fn property(id: &str) -> String {
    let camel = camel_case(id);
    let mut chars = camel.chars();
    match chars.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + chars.as_str(),
        None => camel,
    }
}

/// One message in one catalog as an arrow function, its arguments a single object by name.
fn function(value: &Value, language: &str) -> String {
    let args = arguments(value);
    let signature = if args.is_empty() {
        "()".to_string()
    } else {
        let names = args
            .iter()
            .map(|(name, _)| name.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        let types = args
            .iter()
            .map(|(name, selects)| {
                if *selects {
                    format!("{name}: number")
                } else {
                    format!("{name}: string | number")
                }
            })
            .collect::<Vec<_>>()
            .join("; ");
        format!("({{ {names} }}: {{ {types} }})")
    };

    match value {
        Value::Pattern(parts) => format!("{signature}: string => {}", expression(parts)),
        Value::Select {
            arg,
            variants,
            default,
        } => {
            let others: Vec<&Variant> = variants
                .iter()
                .enumerate()
                .filter(|(index, _)| index != default)
                .map(|(_, variant)| variant)
                .collect();
            if others
                .iter()
                .all(|variant| variant.parts == variants[*default].parts)
            {
                return format!(
                    "{signature}: string => {}",
                    expression(&variants[*default].parts)
                );
            }
            let mut body = format!("{signature}: string => {{\n");
            if others.iter().any(|v| matches!(v.key, Key::Category(_))) {
                body.push_str(&format!(
                    "    const category = plural.{language}.select({arg})\n"
                ));
            }
            for variant in others {
                let condition = match &variant.key {
                    Key::Exact(n) => format!("{arg} === {n}"),
                    Key::Category(c) => format!("category === {}", quoted(c)),
                };
                body.push_str(&format!(
                    "    if ({condition}) return {}\n",
                    expression(&variant.parts)
                ));
            }
            body.push_str(&format!(
                "    return {}\n  }}",
                expression(&variants[*default].parts)
            ));
            body
        }
    }
}

/// The text of a pattern as a TypeScript expression of type `string`.
fn expression(parts: &[Part]) -> String {
    if parts.is_empty() {
        return "''".to_string();
    }
    let pieces: Vec<String> = parts
        .iter()
        .map(|part| match part {
            Part::Text(text) => quoted(text),
            Part::Arg(name) => format!("String({name})"),
        })
        .collect();
    pieces.join(" + ")
}

/// A single-quoted TypeScript string literal.
fn quoted(text: &str) -> String {
    let mut out = String::from("'");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            c if c.is_control() => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generate::load;
    use std::path::Path;

    fn catalog(tag: &str, source: &str) -> Catalog {
        let language = tag.split('-').next().expect("a tag has a language");
        Catalog {
            tag: tag.to_string(),
            language: language.to_string(),
            variant: camel_case(&tag.to_lowercase()),
            messages: parse(source)
                .expect("the fixture parses")
                .into_iter()
                .map(|message| (message.id.clone(), message))
                .collect(),
        }
    }

    /// The window is generated from the catalogs as they stand, and a catalog changed without
    /// the file being written again fails here rather than shipping English in a French window.
    #[test]
    fn the_window_s_messages_are_what_the_catalogs_say() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let catalogs = load(&root.join("locales"), "en-US");
        let generated = typescript(&catalogs, &catalogs[0]);
        let path = root.join(OUTPUT);
        if std::env::var_os("BLESS").is_some() {
            std::fs::write(&path, &generated).expect("write messages.gen.ts");
            return;
        }
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            committed == generated,
            "{} is stale: run `BLESS=1 cargo test -p bravebot-i18n` and commit it",
            path.display()
        );
    }

    /// Only the window's messages go to the window, so the terminal's are not shipped twice.
    #[test]
    fn only_messages_named_for_the_window_are_written() {
        let catalogs = vec![catalog("en-US", "ui-theme = Theme\ncli-usage = Usage:\n")];
        let generated = typescript(&catalogs, &catalogs[0]);
        assert!(
            generated.contains("uiTheme: (): string => 'Theme',"),
            "{generated}"
        );
        assert!(!generated.contains("Usage:"), "{generated}");
    }

    /// A message a translation lacks is the reference's function, words and plural rule both.
    #[test]
    fn a_message_a_translation_omits_is_the_reference_s() {
        let rounds = "ui-rounds = { $count ->\n    [one] { $count } round\n   *[other] { $count } rounds\n    }\n";
        let catalogs = vec![
            catalog("en-US", &format!("ui-theme = Theme\n{rounds}")),
            catalog("fr", "ui-theme = Thème\n"),
        ];
        let generated = typescript(&catalogs, &catalogs[0]);
        assert!(
            generated.contains("uiTheme: (): string => 'Thème',"),
            "{generated}"
        );
        assert!(
            generated.contains("uiRounds: catalogEnUs.uiRounds,"),
            "{generated}"
        );
        assert!(
            generated.contains("plural.en.select(count)") && !generated.contains("plural.fr"),
            "{generated}"
        );
    }

    /// A translation's own plural is formed by its own language's rules (LOCALE-5).
    #[test]
    fn a_plural_is_formed_by_the_rules_of_the_catalog_it_is_written_in() {
        let catalogs = vec![
            catalog(
                "en-US",
                "ui-rounds = { $count ->\n    [0] none\n    [one] { $count } round\n   *[other] { $count } rounds\n    }\n",
            ),
            catalog(
                "fr",
                "ui-rounds = { $count ->\n    [one] { $count } tour\n   *[other] { $count } tours\n    }\n",
            ),
        ];
        let generated = typescript(&catalogs, &catalogs[0]);
        assert!(
            generated.contains("en: new Intl.PluralRules('en')"),
            "{generated}"
        );
        assert!(
            generated.contains("fr: new Intl.PluralRules('fr')"),
            "{generated}"
        );
        assert!(
            generated.contains("if (count === 0) return 'none'"),
            "{generated}"
        );
        assert!(
            generated.contains("if (category === 'one') return String(count) + ' tour'"),
            "{generated}"
        );
        assert!(
            generated.contains("({ count }: { count: number }): string =>"),
            "{generated}"
        );
    }

    /// What a catalog says is text, whatever characters it holds.
    #[test]
    fn a_quote_or_backslash_in_a_message_stays_text() {
        assert_eq!(quoted(r"it's a \ here"), r"'it\'s a \\ here'");
        assert_eq!(property("ui-settings-theme"), "uiSettingsTheme");
    }
}
