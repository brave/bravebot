#!/usr/bin/env python3
"""Check that the implementation matches docs/specs.

Two passes. This script is the first: everything that can be decided without a model,
which is most of the bookkeeping a spec carries. Clause numbering, whether an id still
names the clause it named on main, the tests a clause names, the paths it governs, the
symbols it guards, and the table in the specs README are all facts, and a fact does not
need a review.

    check-spec.py --mechanical-only          the whole first pass, human readable
    check-spec.py --mechanical-only labels   one spec, by name or by id
    check-spec.py --changed                  only specs governing what this branch touched
    check-spec.py --write-unverified         write agents/unverified-clauses.txt from the spec tree

Run with neither --mechanical-only nor --list it also prepares the second pass: a work
directory holding one prompt file per group of clauses, for the conformance review the
check-spec skill drives. Nothing about that pass is decided here; this script writes
files and prints a pointer to them.

    check-spec.py --full                     review every clause in full, ignoring the record
    check-spec.py --threshold 25             review a clause in full from 25% of its lines changed

A clause that docs/check-spec-reviewed holds a verdict for is reviewed only as far as the code it
depends on has changed since the commit the verdict was reached at. `decide` says how far.
"""

